/**
 * The names and the lengths of the two lists the feedback card prints.
 *
 * Since the card knows which strings it printed, a submission may also carry the
 * names on the buttons beside the two positions (`familyName`, `matchName`) and
 * the length of the list the church's position was counted in
 * (`matchRankScope`). No migration adds anything for them, because none of the
 * three is stored: they exist so the worker can tell a position that came from
 * the list this data can print from one that did not -- a doctored body, or a tab
 * left open across a re-seed. A position is a published figure, so it has to name
 * a row of a real list; a name this data does not have is evidence that it does
 * not.
 *
 * The vocabulary is read from the same KV entry `/api/calculate` reads
 * (`denomination_profiles`), because that document *is* the list: the family
 * names are its `families` keys, the church names its `denominations[*]
 * .denomination.name`, and the results page prints exactly those strings (the
 * same `meta.name || meta.denominationname` fallback as `index.ts`). A name that
 * is not in here is therefore not on any card this worker could have served.
 *
 * It caches per isolate the way the profile cache in `index.ts` does, and is
 * deliberately *separate* from it: that cache is filled only by a calculate
 * call, and importing it from `feedback.ts` would make the two modules
 * circular. Being a little stale is harmless -- a renamed family only ever
 * makes the check *stricter* on a position that would have been dropped anyway
 * -- and having nothing at all (KV never seeded, a failed read) degrades to the
 * numeric bounds in `feedback.ts`, which is what that handler did before the
 * names existed.
 */

/** The two name indexes, and which family each church belongs to. */
export type FeedbackVocabulary = {
  /** Canonical family names, keyed by their lowercased spelling. */
  families: Map<string, string>;
  /** Canonical church names, keyed by their lowercased spelling. */
  denominations: Map<string, string>;
  /** The family a church sits in, keyed by the lowercased church name. */
  denominationFamily: Map<string, string>;
};

/** The KV key the data bundle lives under. */
export const PROFILES_KEY = "denomination_profiles";

function emptyVocabulary(): FeedbackVocabulary {
  return { families: new Map(), denominations: new Map(), denominationFamily: new Map() };
}

/**
 * Index a profiles document, tolerating anything.
 *
 * The file is generated by a script and re-written every time the data changes,
 * so this reads it defensively rather than trusting a shape it does not own:
 * entries that are not strings, or a document that is not an object at all,
 * simply contribute nothing. An index that ends up empty is treated as "this
 * data knows no names" by the caller -- it never turns a name into a false
 * negative, it just stops validating.
 */
export function vocabularyFrom(profiles: unknown): FeedbackVocabulary {
  const vocabulary = emptyVocabulary();
  const source = (profiles ?? {}) as { families?: unknown; denominations?: unknown };

  if (source.families && typeof source.families === "object") {
    for (const key of Object.keys(source.families as Record<string, unknown>)) {
      const name = key.trim();
      if (name) vocabulary.families.set(name.toLowerCase(), name);
    }
  }

  if (source.denominations && typeof source.denominations === "object") {
    for (const entry of Object.values(source.denominations as Record<string, unknown>)) {
      const meta = (entry as { denomination?: unknown } | null)?.denomination as
        | { name?: unknown; denominationname?: unknown; family?: unknown }
        | null
        | undefined;
      // The same two spellings the results page reads, in the same order.
      const raw = typeof meta?.name === "string" && meta.name ? meta.name : meta?.denominationname;
      if (typeof raw !== "string") continue;
      const name = raw.trim();
      if (!name) continue;

      vocabulary.denominations.set(name.toLowerCase(), name);
      const family =
        typeof meta?.family === "string"
          ? vocabulary.families.get(meta.family.trim().toLowerCase())
          : undefined;
      if (family) vocabulary.denominationFamily.set(name.toLowerCase(), family);
    }
  }

  return vocabulary;
}

/** Case- and whitespace-insensitive, because a name is the same name either way. */
function lookup(names: Map<string, string>, value: unknown): string | null {
  if (typeof value !== "string") return null;
  const key = value.trim().toLowerCase();
  return key ? names.get(key) ?? null : null;
}

/** The canonical family name behind a submitted one, or null if this data has no such family. */
export function lookupFamily(vocabulary: FeedbackVocabulary | null, value: unknown): string | null {
  return vocabulary ? lookup(vocabulary.families, value) : null;
}

/** The canonical church name behind a submitted one, or null if this data has no such church. */
export function lookupDenomination(
  vocabulary: FeedbackVocabulary | null,
  value: unknown
): string | null {
  return vocabulary ? lookup(vocabulary.denominations, value) : null;
}

/** Which family a church sits in, or null when the data does not place it. */
export function familyOfDenomination(
  vocabulary: FeedbackVocabulary | null,
  denomination: string
): string | null {
  return vocabulary ? vocabulary.denominationFamily.get(denomination.toLowerCase()) ?? null : null;
}

let cached: FeedbackVocabulary | null = null;
let inFlight: Promise<FeedbackVocabulary | null> | null = null;

/**
 * The index for this isolate, or null when there is nothing to read.
 *
 * A null result is not remembered, so a KV namespace seeded later -- or a read
 * that failed -- is picked up by the next submission instead of leaving the
 * worker unvalidated until it is recycled. A successful read is remembered for
 * as long as the isolate lives, the same bargain `cachedProfiles` makes for the
 * results page: the bundle changes when a script is run, not between two
 * requests.
 */
export function loadVocabulary(env: {
  THEOCOMPASS_CACHE?: KVNamespace;
}): Promise<FeedbackVocabulary | null> {
  if (cached) return Promise.resolve(cached);
  const kv = env.THEOCOMPASS_CACHE;
  if (!kv) return Promise.resolve(null);
  if (!inFlight) {
    inFlight = kv
      .get(PROFILES_KEY, "json")
      .then((profiles) => (profiles ? vocabularyFrom(profiles) : null))
      .catch(() => null)
      .then((vocabulary) => {
        inFlight = null;
        if (vocabulary) cached = vocabulary;
        return vocabulary;
      });
  }
  return inFlight;
}

/**
 * Forget what this isolate knows. For tests, which seed their own bundle into an
 * in-memory namespace between cases; production never has a reason to.
 */
export function resetVocabularyCache(): void {
  cached = null;
  inFlight = null;
}
