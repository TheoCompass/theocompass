#!/usr/bin/env python3
"""Turn `data/roadmap.json` into `theocompass-api/roadmap_seed.sql`.

The generated SQL upserts phases and tasks so re-running it after a content
change keeps D1 in sync without touching the database by hand. The `status`
column is deliberately left out of the upsert: a moderator's edit on /roadmap
must survive a spreadsheet re-sync. Pass --reset-status to force the
spreadsheet's own statuses back (first install, or a deliberate reset).

Usage:
    python3 scripts/generate_roadmap_seed.py
    python3 scripts/generate_roadmap_seed.py --reset-status
"""

import argparse
import json
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.dirname(SCRIPT_DIR)
SOURCE_JSON = os.path.join(ROOT_DIR, "data", "roadmap.json")
DEFAULT_OUT = os.path.join(ROOT_DIR, "theocompass-api", "roadmap_seed.sql")

STATUSES = ("not_started", "in_progress", "implemented_local", "implemented_live")


def sql_literal(value):
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", default=SOURCE_JSON, help="input roadmap JSON")
    parser.add_argument("--out", default=DEFAULT_OUT, help="output SQL path")
    parser.add_argument(
        "--reset-status",
        action="store_true",
        help="also overwrite status from the sheet (skips mod edits)",
    )
    args = parser.parse_args()

    with open(args.json, encoding="utf-8") as handle:
        document = json.load(handle)

    phases = document["phases"]
    lines = [
        "-- Generated by scripts/generate_roadmap_seed.py -- do not edit by hand.",
        f"-- Source: data/{document.get('source', 'roadmap.json')}",
        "-- Safe to re-run: phases/tasks upsert by key and removed rows are deleted.",
    ]
    if args.reset_status:
        lines.append("-- --reset-status: task statuses mirror the spreadsheet.")
    else:
        lines.append("-- Statuses are preserved; only content columns are updated.")
    lines.append("")

    for phase in phases:
        values = ", ".join(
            [
                str(phase["index"]),
                sql_literal(phase["title"]),
                sql_literal(phase["label"]),
                sql_literal(phase["goal"]),
            ]
        )
        lines.append(
            "INSERT INTO roadmap_phases (phase_index, title, label, goal) "
            f"VALUES ({values})\n"
            "ON CONFLICT(phase_index) DO UPDATE SET "
            "title = excluded.title, label = excluded.label, goal = excluded.goal, "
            "updated_at = datetime('now');"
        )

    lines.append("")

    for phase in phases:
        for task in phase["tasks"]:
            status = task.get("status") or "not_started"
            if status not in STATUSES:
                raise SystemExit(f"{task['id']}: unexpected status {status!r}")
            values = ", ".join(
                [
                    sql_literal(task["id"]),
                    str(phase["index"]),
                    str(task["index"]),
                    sql_literal(task["sheetId"]),
                    sql_literal(task["name"]),
                    sql_literal(task["description"]),
                    sql_literal(task.get("type") or None),
                    sql_literal(task.get("role") or None),
                    sql_literal(status),
                ]
            )
            update = [
                "phase_index = excluded.phase_index",
                "task_index = excluded.task_index",
                "sheet_id = excluded.sheet_id",
                "name = excluded.name",
                "description = excluded.description",
                "type = excluded.type",
                "owner_role = excluded.owner_role",
            ]
            if args.reset_status:
                update.append("status = excluded.status")
            update.append("updated_at = datetime('now')")
            lines.append(
                "INSERT INTO roadmap_tasks "
                "(id, phase_index, task_index, sheet_id, name, description, type, owner_role, status) "
                f"VALUES ({values})\n"
                "ON CONFLICT(id) DO UPDATE SET " + ", ".join(update) + ";"
            )

    lines.append("")

    task_ids = ", ".join(sql_literal(t["id"]) for p in phases for t in p["tasks"])
    phase_indexes = ", ".join(str(p["index"]) for p in phases)
    lines.append(f"DELETE FROM roadmap_tasks WHERE id NOT IN ({task_ids});")
    lines.append(f"DELETE FROM roadmap_phases WHERE phase_index NOT IN ({phase_indexes});")
    lines.append("")

    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))

    task_count = sum(len(p["tasks"]) for p in phases)
    print(f"Wrote {args.out}")
    print(f"  phases: {len(phases)}  tasks: {task_count}")
    print(f"  status reset: {'yes' if args.reset_status else 'no (mod edits preserved)'}")


if __name__ == "__main__":
    main()
