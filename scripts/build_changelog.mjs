#!/usr/bin/env node
/**
 * Build the changelog snapshot from the Git history.
 *
 * `frontend/app/changelog` is a static page: it imports
 * `frontend/lib/changelog.generated.ts` and renders it during `next build`, so
 * the deployed HTML is crawlable and needs no worker route, no KV namespace and
 * no secret. This script is what keeps that file true.
 *
 * Reading the history lives in `scripts/lib/changelog-commits.mjs`, because the
 * Reddit digest drafts from the same entries: one definition of "a product
 * change", two consumers, no way for the post to contradict the page.
 *
 * Output is deterministic: the same history produces a byte-identical file, so
 * a rebuild makes no diff and `--check` can gate a future CI job. That is why
 * the generated file carries the newest commit's date rather than the wall
 * clock — "up to 21 Nov 2026" is a fact about the data, not about the build.
 *
 * Failure is soft on purpose: no network, a 403 from a rate limit or a missing
 * `git` keeps the previous snapshot and exits 0. A changelog is not worth a
 * failed deploy — but it is worth a warning, and `--check` turns the staleness
 * into a red build once someone wires it up.
 *
 * Usage:
 *   node scripts/build_changelog.mjs           # refresh the snapshot
 *   node scripts/build_changelog.mjs --check   # exit 1 if it is stale
 *   node scripts/build_changelog.mjs --offline # git only, no HTTP
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BRANCH, ROOT, collectEntries } from "./lib/changelog-commits.mjs";

const OUTPUT = join(ROOT, "frontend", "lib", "changelog.generated.ts");
const OUTPUT_TASKS = join(ROOT, "frontend", "lib", "changelog-tasks.generated.ts");

/** A product change is anything that is not chore/ci/build or a noise merge. */
const DAY = 86_400_000;

const args = new Set(process.argv.slice(2));
const CHECK = args.has("--check");
const OFFLINE = args.has("--offline");
const QUIET = args.has("--quiet");

function log(message) {
  if (!QUIET) console.log(message);
}

function warn(message) {
  console.warn(`changelog: ${message}`);
}


// --- the files -------------------------------------------------------------

const ENTRIES_FILE_HEADER = `// Generated by \`node scripts/build_changelog.mjs\` — do not edit by hand.
//
// One row per commit on \`${BRANCH}\`, newest first, with \`feat(scope): …\`
// split into its parts and \`Task: p0-01\` trailers resolved against
// data/roadmap.json. Regenerate after a push (\`npm run changelog\` in
// \`frontend/\`); the page that reads it is \`app/changelog/page.tsx\`.
//
// Read by the server only. The roadmap's "Latest" lines come from the second
// file below instead, so a client component never bundles these entries.
`;

const LATEST_FILE_HEADER = `// Generated by \`node scripts/build_changelog.mjs\` — do not edit by hand.
//
// What a client component may know about the changelog: the newest commit that
// names each roadmap task, and three numbers for the landing page's facts row.
// Small on purpose — \`app/page.tsx\` is a client component, and 70 KB of commit
// bodies has no business in that bundle.
`;

/** `frontend/lib/changelog.generated.ts` — the whole page's data. */
function renderEntries(entries) {
  // "Current up to" is the newest commit, not the wall clock, so a rebuild with
  // no new commits produces no diff.
  const newest = entries[0]?.date ?? "1970-01-01T00:00:00.000Z";

  return `${ENTRIES_FILE_HEADER}
import type { ChangelogEntry } from "./changelog";

/** The newest commit's date: "the changelog is current up to here". */
export const GENERATED_AT = ${JSON.stringify(newest)};

export const ENTRIES: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

/** The first (newest) entry per task id, in the order the tasks were seen. */
function latestByTask(entries) {
  const latest = {};
  for (const entry of entries) {
    for (const task of entry.tasks) {
      if (!latest[task.id]) {
        latest[task.id] = { short: entry.short, date: entry.date, subject: entry.subject };
      }
    }
  }
  return latest;
}

/**
 * Three counts for the landing page, measured from the newest commit so a
 * rebuild with no new work reports the same numbers.
 *
 * `last30d` answers "is this alive?" better than any adjective: it is the one
 * claim on the page a visitor can verify by clicking through to the entries.
 */
function summarise(entries) {
  const newest = entries[0]?.date ?? "1970-01-01T00:00:00.000Z";
  const anchor = Date.parse(newest);
  const product = entries.filter((entry) => !entry.housekeeping);
  const within = (days) =>
    product.filter((entry) => anchor - Date.parse(entry.date) <= days * DAY).length;

  return { last7d: within(7), last30d: within(30), latest: newest };
}

/** `frontend/lib/changelog-tasks.generated.ts` — what `/roadmap` and `/` need. */
function renderLatest(latest, summary) {
  return `${LATEST_FILE_HEADER}
import type { LatestCommit } from "./changelog";

export const CHANGELOG_SUMMARY = ${JSON.stringify(summary, null, 2)};

export const LATEST_BY_TASK: Partial<Record<string, LatestCommit>> = ${JSON.stringify(latest, null, 2)};
`;
}


// --- main ------------------------------------------------------------------

async function main() {
  const { entries, unresolved } = await collectEntries({ offline: OFFLINE, log, warn });

  if (entries.length === 0) {
    warn("no commits found; leaving the snapshot untouched");
    return 0;
  }

  const product = entries.filter((entry) => !entry.housekeeping).length;
  const linked = entries.filter((entry) => entry.tasks.length > 0).length;
  log(
    `changelog: ${entries.length} entries (${product} product, ${
      entries.length - product
    } housekeeping, ${linked} linked to a task)`
  );
  if (unresolved.size > 0) {
    warn(`unresolved Task: ${[...unresolved].join(", ")} — no matching id or sheet number`);
  }

  const next = renderEntries(entries);
  const nextTasks = renderLatest(latestByTask(entries), summarise(entries));
  const previous = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  const previousTasks = existsSync(OUTPUT_TASKS) ? readFileSync(OUTPUT_TASKS, "utf8") : "";

  if (next === previous && nextTasks === previousTasks) {
    log("changelog: snapshot already current");
    return 0;
  }

  if (CHECK) {
    warn("snapshot is stale; run `node scripts/build_changelog.mjs`");
    return 1;
  }

  writeFileSync(OUTPUT, next);
  writeFileSync(OUTPUT_TASKS, nextTasks);
  log(`changelog: wrote ${OUTPUT}`);
  log(`changelog: wrote ${OUTPUT_TASKS}`);
  return 0;
}

main().then(
  (code) => process.exit(code),
  (error) => {
    warn(`unexpected failure: ${error.stack ?? error.message}; snapshot left untouched`);
    process.exit(0);
  }
);
